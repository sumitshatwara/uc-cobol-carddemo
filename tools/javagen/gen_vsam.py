#!/usr/bin/env python3
"""Generate the PostgreSQL tables and JPA entities that stand in for the
VSAM / sequential datasets shared by the batch slices.

    python3 tools/javagen/gen_vsam.py            # rewrite the generated files
    python3 tools/javagen/gen_vsam.py --check    # exit 1 when they are stale

Layouts come from the copybooks through tools/parity/copybook.py, so column
widths and numeric scale are exactly the PIC clauses:

* PIC X(n)                -> VARCHAR(n) COLLATE "C"  (byte order = VSAM key order;
                             stored right-trimmed, re-padded on export)
* PIC [S]9(p)  (scale 0)  -> BIGINT           (Long)
* PIC [S]9(p)V9(s)        -> NUMERIC(p+s, s)  (BigDecimal, never double)

FILLER is not stored.  The generated table registry (DatasetTables.java) maps
each fixture DSN to its copybook, table and key so the generic loader and
exporter in java/common need no per-slice code.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.parity.copybook import parse_copybook  # noqa: E402

# table, copybook, entity, key columns (copybook field names), sequential?
TABLES = [
    ("account",          "CVACT01Y", "Account",         ["ACCT-ID"], False),
    ("card_xref",        "CVACT03Y", "CardXref",        ["XREF-CARD-NUM"], False),
    ("tran_cat_balance", "CVTRA01Y", "TranCatBalance",  ["TRANCAT-ACCT-ID", "TRANCAT-TYPE-CD", "TRANCAT-CD"], False),
    ("disclosure_group", "CVTRA02Y", "DisclosureGroup", ["DIS-ACCT-GROUP-ID", "DIS-TRAN-TYPE-CD", "DIS-TRAN-CAT-CD"], False),
    ("tran_type",        "CVTRA03Y", "TranType",        ["TRAN-TYPE"], False),
    ("tran_category",    "CVTRA04Y", "TranCategory",    ["TRAN-TYPE-CD", "TRAN-CAT-CD"], False),
    ("transact",         "CVTRA05Y", "Transact",        ["TRAN-ID"], False),
    ("daily_tran",       "CVTRA06Y", "DailyTran",       [], True),
]

# fixture input DSN -> table (datasets not listed are kept only as raw lines in fixture_record)
DSN_TABLES = {
    "AWS.M2.CARDDEMO.ACCTDATA.PS": "account",
    "AWS.M2.CARDDEMO.CARDXREF.PS": "card_xref",
    "AWS.M2.CARDDEMO.TCATBALF.PS": "tran_cat_balance",
    "AWS.M2.CARDDEMO.DISCGRP.PS": "disclosure_group",
    "AWS.M2.CARDDEMO.TRANTYPE.PS": "tran_type",
    "AWS.M2.CARDDEMO.TRANCATG.PS": "tran_category",
    "AWS.M2.CARDDEMO.DALYTRAN.PS": "daily_tran",
    "AWS.M2.CARDDEMO.DALYTRAN.PS.INIT": "transact",
}

SQL_OUT = ROOT / "java/common/src/main/resources/db/migration/common/V001__vsam_dataset_tables.sql"
JAVA_PKG = "com.carddemo.common.entity"
JAVA_DIR = ROOT / "java/common/src/main/java/com/carddemo/common/entity"


def column(name: str) -> str:
    return name.lower().replace("-", "_")


def camel(name: str, upper: bool = False) -> str:
    parts = name.lower().split("-")
    s = parts[0] + "".join(p.capitalize() for p in parts[1:])
    return s[0].upper() + s[1:] if upper else s


def sql_type(f) -> str:
    if f.kind == "text":
        return f"VARCHAR({f.length}) COLLATE \"C\""
    if f.scale == 0:
        return "BIGINT"
    return f"NUMERIC({f.digits},{f.scale})"


def java_type(f) -> str:
    if f.kind == "text":
        return "String"
    return "Long" if f.scale == 0 else "BigDecimal"


def fields_of(copybook):
    return [f for f in parse_copybook(copybook) if not f.is_filler]


def gen_sql() -> str:
    out = ["-- GENERATED by tools/javagen/gen_vsam.py from the copybooks; do not edit by hand.",
           "-- PostgreSQL stand-ins for the VSAM KSDS / sequential datasets used by the batch chains.",
           "-- Column = copybook field (lower snake case); FILLER is not stored.",
           "CREATE SCHEMA IF NOT EXISTS carddemo;", ""]
    for table, cpy, _, keys, seq in TABLES:
        cols = []
        if seq:
            cols.append("    rec_seq INTEGER NOT NULL")
        for f in fields_of(cpy):
            cols.append(f"    {column(f.name)} {sql_type(f)} NOT NULL")
        pk = ["rec_seq"] if seq else [column(k) for k in keys]
        cols.append(f"    PRIMARY KEY ({', '.join(pk)})")
        out.append(f"-- {cpy} ({'sequential' if seq else 'KSDS'})")
        out.append(f"CREATE TABLE carddemo.{table} (\n" + ",\n".join(cols) + "\n);\n")
    out.append("-- every fixture input record, verbatim, in file order (layouts without a table: DATEPARM, INPFILE, DYNSQL)")
    out.append("CREATE TABLE carddemo.fixture_record (\n    dsn VARCHAR(64) NOT NULL,\n    rec_seq INTEGER NOT NULL,\n"
               "    data VARCHAR(1000) COLLATE \"C\" NOT NULL,\n    PRIMARY KEY (dsn, rec_seq)\n);\n")
    return "\n".join(out)


def gen_entity(table, cpy, entity, keys, seq) -> dict[str, str]:
    fs = fields_of(cpy)
    composite = len(keys) > 1
    imports = {"jakarta.persistence.Column", "jakarta.persistence.Entity", "jakarta.persistence.Id",
               "jakarta.persistence.Table"}
    if any(java_type(f) == "BigDecimal" for f in fs):
        imports.add("java.math.BigDecimal")
    if composite:
        imports.add("jakarta.persistence.IdClass")
    body = [f"/** Row of carddemo.{table}: copybook {cpy}. GENERATED by tools/javagen/gen_vsam.py. */",
            "@Entity", f'@Table(schema = "carddemo", name = "{table}")']
    if composite:
        body.append(f"@IdClass({entity}.Key.class)")
    body.append(f"public class {entity} {{")
    if composite:
        kf = [f for f in fs if f.name in keys]
        args = ", ".join(f"{java_type(f)} {camel(f.name)}" for f in kf)
        body.append(f"\n    /** Composite key ({', '.join(keys)}). */")
        body.append(f"    public record Key({args}) implements java.io.Serializable {{\n        public Key() {{ this({', '.join('null' for _ in kf)}); }}\n    }}")
    if seq:
        body += ["", "    /** Position of the record in the sequential file (1-based). */",
                 "    @Id", '    @Column(name = "rec_seq", nullable = false)', "    private Integer recSeq;"]
    for f in fs:
        body.append("")
        pic = f"PIC {'S' if f.signed else ''}{'X' if f.kind == 'text' else '9'}({f.length if f.kind == 'text' else f.digits - f.scale})" + (f"V9({f.scale})" if f.scale else "")
        body.append(f"    /** {f.name} {pic}. */")
        if f.name in keys:
            body.append("    @Id")
        extra = f", precision = {f.digits}, scale = {f.scale}" if java_type(f) == "BigDecimal" else (f", length = {f.length}" if f.kind == "text" else "")
        body.append(f'    @Column(name = "{column(f.name)}", nullable = false{extra})')
        body.append(f"    private {java_type(f)} {camel(f.name)};")
    allf = ([("Integer", "recSeq")] if seq else []) + [(java_type(f), camel(f.name)) for f in fs]
    for t, n in allf:
        cap = n[0].upper() + n[1:]
        body.append(f"\n    public {t} get{cap}() {{ return {n}; }}")
        body.append(f"    public void set{cap}({t} {n}) {{ this.{n} = {n}; }}")
    body.append("}")
    src = f"package {JAVA_PKG};\n\n" + "\n".join(f"import {i};" for i in sorted(imports)) + "\n\n" + "\n".join(body) + "\n"
    return {f"{entity}.java": src}


def gen_registry() -> str:
    lines = [f"package {JAVA_PKG};", "", "import java.util.List;", "import java.util.Map;", "",
             "/** Dataset -> table registry. GENERATED by tools/javagen/gen_vsam.py; do not edit by hand. */",
             "public final class DatasetTables {", "", "    private DatasetTables() {}", "",
             "    /** A table that stands in for a VSAM / sequential dataset. */",
             "    public record TableDef(String table, String copybook, List<String> keyColumns, boolean sequential) {",
             "        public String qualified() { return \"carddemo.\" + table; }",
             "        public String orderBy() { return String.join(\", \", keyColumns); }", "    }", ""]
    for table, cpy, _, keys, seq in TABLES:
        kc = ['"rec_seq"'] if seq else [f'"{column(k)}"' for k in keys]
        lines.append(f'    public static final TableDef {table.upper()} = new TableDef("{table}", "{cpy}", List.of({", ".join(kc)}), {str(seq).lower()});')
    lines += ["", "    /** Every table, in dependency-free order. */",
              f"    public static final List<TableDef> ALL = List.of({', '.join(t[0].upper() for t in TABLES)});", "",
              "    /** Fixture input DSN -> table it is loaded into. */",
              "    public static final Map<String, TableDef> BY_INPUT_DSN = Map.of("]
    items = [f'        "{d}", {t.upper()}' for d, t in DSN_TABLES.items()]
    lines.append(",\n".join(items))
    lines += ["    );", "}"]
    return "\n".join(lines) + "\n"


def outputs() -> dict[Path, str]:
    files = {SQL_OUT: gen_sql(), JAVA_DIR / "DatasetTables.java": gen_registry()}
    for t in TABLES:
        for name, src in gen_entity(*t).items():
            files[JAVA_DIR / name] = src
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = []
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("stale generated files (run python3 tools/javagen/gen_vsam.py):\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
